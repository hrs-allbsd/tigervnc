#!/usr/bin/env python3
"""Compare installed libsixel output policies on deterministic indexed fixtures.

This counts generated bytes, not terminal paint time or network throughput.
Pixel correctness is checked separately by the viewer's xterm protocol matrix.
"""
import argparse
import ctypes as C
import ctypes.util
import hashlib
import json
from pathlib import Path
import random
import statistics
import subprocess
import time

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--report', type=Path, required=True)
parser.add_argument('--samples', type=int, default=9)
args = parser.parse_args()
if not 3 <= args.samples <= 31:
    parser.error('--samples must be 3..31')
args.report.unlink(missing_ok=True)
args.report.parent.mkdir(parents=True, exist_ok=True)
lib = C.CDLL(ctypes.util.find_library('sixel'))
callback_type = C.CFUNCTYPE(C.c_int,C.c_void_p,C.c_int,C.c_void_p)
def function(name, result, *parameters):
    f = getattr(lib,name); f.restype = result; f.argtypes = parameters
    return f
output_new = function('sixel_output_new',C.c_int,C.POINTER(C.c_void_p),callback_type,C.c_void_p,C.c_void_p)
output_unref = function('sixel_output_unref',None,C.c_void_p)
policy_set = function('sixel_output_set_encode_policy',None,C.c_void_p,C.c_int)
dither_new = function('sixel_dither_new',C.c_int,C.POINTER(C.c_void_p),C.c_int,C.c_void_p)
dither_unref = function('sixel_dither_unref',None,C.c_void_p)
palette_set = function('sixel_dither_set_palette',None,C.c_void_p,C.c_void_p)
format_set = function('sixel_dither_set_pixelformat',None,C.c_void_p,C.c_int)
diffuse_set = function('sixel_dither_set_diffusion_type',None,C.c_void_p,C.c_int)
body_set = function('sixel_dither_set_body_only',None,C.c_void_p,C.c_int)
encode = function('sixel_encode',C.c_int,C.c_void_p,C.c_int,C.c_int,C.c_int,C.c_void_p,C.c_void_p)
def checked(status):
    if status & 0x1000: raise RuntimeError(f'libsixel status {status}')

def measure(image, width, height, colors, palette, policy):
    output, dither = C.c_void_p(), C.c_void_p()
    count = 0
    @callback_type
    def sink(data, length, context):
        nonlocal count
        if length < 0 or count+length > 32*1024*1024: return -1
        count += length
        return length
    started = time.perf_counter_ns()
    try:
        checked(output_new(C.byref(output),sink,None,None))
        if policy is not None: policy_set(output,policy)
        checked(dither_new(C.byref(dither),colors,None))
        palette_set(dither,palette)
        format_set(dither,0x83)  # SIXEL_PIXELFORMAT_PAL8
        diffuse_set(dither,1)   # SIXEL_DIFFUSE_NONE
        body_set(dither,0)
        checked(encode(image,width,height,1,dither,output))
    finally:
        if dither: dither_unref(dither)
        if output: output_unref(output)
    return (time.perf_counter_ns()-started)/1e6,count

policies = [('default',None),('fast',1),('size',2)]
results = []
for colors in (8,256):
    palette = bytes(channel for i in range(colors) for channel in
        ((255 if i&4 else 0,255 if i&2 else 0,255 if i&1 else 0) if colors==8
         else (((i>>5)&7)*255//7,((i>>2)&7)*255//7,(i&3)*255//3)))
    palette_buffer = C.create_string_buffer(palette)
    for name,width,height in [('solid',599,431),('checker',599,431),('bands',599,431),
                              ('noise',599,431),('thin',599,7),('small',48,48)]:
        source = random.Random(0)
        image = bytes((colors//2 if name=='solid' else
            ((colors-1) if (x//16+y//16)%2 else 0) if name=='checker' else
            source.randrange(colors) if name=='noise' else (x//4+y//4)%colors)
            for y in range(height) for x in range(width))
        buffer = C.create_string_buffer(image)
        timings = {key:[] for key,_ in policies}
        sizes = {key:set() for key,_ in policies}
        # Warm every policy, then rotate order to reduce systematic drift.
        for _,policy in policies: measure(buffer,width,height,colors,palette_buffer,policy)
        for sample in range(args.samples):
            for offset in range(len(policies)):
                key,policy = policies[(sample+offset)%len(policies)]
                elapsed,size = measure(buffer,width,height,colors,palette_buffer,policy)
                timings[key].append(elapsed); sizes[key].add(size)
        assert all(len(values)==1 for values in sizes.values()), sizes
        results.append({'case':name,'width':width,'height':height,'colors':colors,
            'input_sha256':hashlib.sha256(image).hexdigest(),
            'policies':{key:{'bytes':next(iter(sizes[key])),
                'median_ms':statistics.median(timings[key]),'samples_ms':timings[key]}
                for key,_ in policies}})
version = subprocess.check_output(['pkg-config','--modversion','libsixel'],text=True).strip()
args.report.write_text(json.dumps({'libsixel_version':version,'samples':args.samples,
    'cases':results,'scope':'Synthetic PAL8 encode/object lifetime with Python callback; '
    'no terminal paint, transport, RGB quantization or pixel comparison'},indent=2)+'\n')
print(f'PASS: {len(results)} fixtures, {args.samples} samples per policy')
